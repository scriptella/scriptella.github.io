// Run with node tools/build-etl-viewer.mjs after editing the template or shared styles/highlighter.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const read = (path) => readFileSync(new URL(path, root), "utf8");

function section(text, start, end) {
  const from = text.indexOf(start);
  const to = text.indexOf(end, from + start.length);
  if (from < 0 || to < 0) throw new Error("Could not find shared viewer resources");
  return text.slice(from, to).trimEnd();
}

const css = read("style.css");
const styles = [
  section(css, ":root {", "a {"),
  section(css, "code,\nkbd,", ".note,\n.warning")
].join("\n\n");
const theme = read("theme.js");
const highlighter = [
  section(theme, "  function appendToken(", "  var javaKeywords"),
  section(theme, "  function highlightXmlTag(", "  function initializeSyntaxHighlighting")
].join("\n\n");

const sample = `<!DOCTYPE etl SYSTEM "http://scriptella.org/dtd/etl.dtd">
<etl>
  <connection driver="h2" url="jdbc:h2:mem:demo"/>
  <script>
    CREATE TABLE people (id INT, name VARCHAR(100));
    INSERT INTO people VALUES (1, 'Ada');
  </script>
</etl>`;

const viewer = read("templates/etl-viewer.html")
  .replace("<!-- SHARED_STYLES -->", () => styles)
  .replace("<!-- SHARED_HIGHLIGHTER -->", () => highlighter)
  .replace("<!-- SAMPLE_XML -->", () => JSON.stringify(sample).replaceAll("<", "\\u003c"));
writeFileSync(new URL("tools/etl-viewer.html", root),
  "<!-- Generated by tools/build-etl-viewer.mjs. Edit templates/etl-viewer.html. -->\n" + viewer);
